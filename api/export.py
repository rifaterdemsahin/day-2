"""Export terms to plain JSON documents (the files in assets/terms/ and GET /api/export).

The database is the source of truth; exported files are generated, committed to git as a
backup and read by the site build, so builds work offline. Never edit them by hand.
"""
import json

NOTE = "Generated by scripts/export_terms.py from the term database. Do not edit by hand: edit the term in the site."
TERM_ORDER = ["slug", "term", "status", "hook", "definition", "analogy", "chosen_title", "title_options", "voice_lines",
              "rewatch_pct", "views", "publish_date", "youtube_url"]
SCENE_ORDER = ["n", "start", "end", "vo", "visual", "on_screen_text", "prompt", "hf_camera", "clip_status"]


def term_doc(con, slug):
    r = con.execute("SELECT * FROM terms WHERE slug=?", (slug,)).fetchone()
    if r is None:
        raise KeyError(slug)
    d = {"_note": NOTE}
    for k in TERM_ORDER:
        d[k] = json.loads(r[k]) if k in ("title_options", "voice_lines") else r[k]
    d["scenes"] = [{k: s[k] for k in SCENE_ORDER} for s in
                   con.execute("SELECT * FROM scenes WHERE term_slug=? ORDER BY n", (slug,))]
    return d  # updated_at is left out on purpose: it would make every export a git diff


def all_docs(con):
    return {r["slug"]: term_doc(con, r["slug"]) for r in con.execute("SELECT slug FROM terms ORDER BY slug")}


def dumps(doc):
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
