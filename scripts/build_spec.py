#!/usr/bin/env python3
"""Join spec/*.md into MASTER_SPEC.md (GENERATED, git-ignored, for humans and the Spec page).

  python3 -I scripts/build_spec.py

Edit spec/rules.md, spec/part-a-long.md or spec/part-b-short.md, never MASTER_SPEC.md.
Agents: do not read the generated file; read only the one spec/*.md the task needs.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PARTS = ["rules.md", "part-a-long.md", "part-b-short.md"]
head = "<!-- GENERATED by scripts/build_spec.py from spec/*.md. Do not edit: edit the files in spec/. -->\n\n"
text = head + "\n".join((ROOT / "spec" / p).read_text(encoding="utf-8").rstrip("\n") + "\n" for p in PARTS)
(ROOT / "MASTER_SPEC.md").write_text(text, encoding="utf-8")
print(f"📖 MASTER_SPEC.md generated from {len(PARTS)} files ({len(text) // 4} tokens, for humans)")
